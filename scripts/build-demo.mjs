// Builds demo/ai-threads.js: ai-threads' own modules from src/, unchanged, wrapped so a browser can run
// them, with the stand-ins in scripts/browser-shims/ for the parts of Node they use (a file system in
// memory, POSIX paths, Buffer, os, crypto). The demo runs the real library on that.
//
// `npm run demo` serves the bundle fresh from src/ on every request; `npm run build:demo` writes the
// file, which pages.yml does before it publishes the demo. The file is not committed.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

/** The stand-ins, under the names the library requires them by. */
const SHIMS = {
  buffer: 'scripts/browser-shims/buffer.js',
  path: 'scripts/browser-shims/path.js',
  fs: 'scripts/browser-shims/fs.js',
  'node-shims': 'scripts/browser-shims/node.js',
};

/** The library's modules the demo needs: the core with its inbox and threads, the view, the hooks. */
const MODULES = [
  'src/util.js', 'src/markup.js', 'src/config.js', 'src/registry.js', 'src/command.js', 'src/core.js', 'src/view.js',
  'src/claude-code/transcript.js', 'src/claude-code/hooks.js',
];

// Runs in the browser: a small CommonJS loader over the modules above.
const LOADER = `
const cache = Object.create(null);
const ALIASES = { os: 'os', crypto: 'crypto', child_process: 'childProcess' };
const dirOf = (id) => id.slice(0, id.lastIndexOf('/')) || '/';
function resolveId(from, request) {
  if (!request.startsWith('.')) return request;
  const out = [];
  for (const part of \`\${dirOf(from)}/\${request}\`.split('/')) {
    if (!part || part === '.') continue;
    if (part === '..') out.pop();
    else out.push(part);
  }
  const base = \`/\${out.join('/')}\`;
  const found = [base, \`\${base}.js\`, \`\${base}/index.js\`].find((id) => defs[id]);
  if (!found) throw new Error(\`ai-threads demo: \${request} (required by \${from}) is not in the bundle\`);
  return found;
}
function load(id) {
  if (ALIASES[id]) return load('node-shims')[ALIASES[id]];
  if (cache[id]) return cache[id].exports;
  if (!defs[id]) throw new Error(\`ai-threads demo: \${id} is not in the bundle\`);
  const module = { exports: {} };
  cache[id] = module;
  const req = (request) => load(resolveId(id, request));
  if (shims[id]) defs[id].call(module.exports, module, module.exports, req, id, dirOf(id));
  else defs[id].call(module.exports, module, module.exports, req, id, dirOf(id), load('node-shims').process, load('buffer').Buffer);
  return module.exports;
}
`;

const read = async (file) => (await readFile(`${root}${file}`, 'utf8')).split('\r').join('');

/** The bundle, as a string: one classic script that defines window.AiThreads. */
export async function buildDemo() {
  const { version } = JSON.parse(await read('package.json'));
  const defs = [];
  for (const [id, file] of Object.entries(SHIMS)) {
    defs.push(`// ${file}\ndefs[${JSON.stringify(id)}] = function (module, exports, require, __filename, __dirname) {\n${await read(file)}};`);
  }
  for (const file of MODULES) {
    defs.push(`// ${file}\ndefs[${JSON.stringify(`/${file}`)}] = function (module, exports, require, __filename, __dirname, process, Buffer) {\n${await read(file)}};`);
  }
  return `/*! ai-threads v${version} for the browser demo | MIT | https://github.com/rbritta/ai-threads
 * Generated by scripts/build-demo.mjs from src/ and scripts/browser-shims/: do not edit. */
(function () {
'use strict';
const defs = Object.create(null);
const shims = ${JSON.stringify(Object.fromEntries(Object.keys(SHIMS).map((id) => [id, true])))};
${defs.join('\n\n')}
${LOADER}
const core = load('/src/core.js');
globalThis.AiThreads = {
  version: ${JSON.stringify(version)},
  open: core.open,
  markup: load('/src/markup.js'),
  makeHooks: load('/src/claude-code/hooks.js').makeHooks,
  fs: load('fs'),
};
})();
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const out = await buildDemo();
  await writeFile(`${root}demo/ai-threads.js`, out);
  console.log(`demo/ai-threads.js (${(out.length / 1024).toFixed(1)} kB)`);
}
